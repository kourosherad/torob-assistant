import { product } from './catalog.mjs';

export function cleanQuestions(questions) {
  if (!Array.isArray(questions) || questions.length > 2) throw Error('حداکثر دو سؤال مجاز است.');
  return questions.map((q) => {
    if (
      typeof q.question !== 'string' ||
      !q.question.trim() ||
      q.question.length > 300 ||
      !Array.isArray(q.options)
    )
      throw Error('ساختار سؤال معتبر نیست.');
    const options = [
      ...new Set(
        q.options
          .filter((x) => typeof x === 'string')
          .map((x) => x.trim())
          .filter((x) => x && x.length <= 100 && x !== 'سایر'),
      ),
    ].slice(0, 6);
    if (options.length < 2) throw Error('سؤال باید دست‌کم دو گزینه داشته باشد.');
    return { question: q.question.trim(), options };
  });
}

// Product names, images and price ranges are loaded from SQL, never generated by the model.
export function presentUi(ui) {
  return {
    notice: ui?.notice || '',
    products: (ui?.productIds || []).slice(0, 6).map(product).filter(Boolean),
    questions: ui?.questions || [],
  };
}
